---The editor services the core is given. Callbacks are always called on the
---main loop, where the editor can be used freely.
---@class jin.Host
---@field name "nvim"|"vim"
---Run `argv` without a shell; `on_exit` receives its whole output. `env`
---adds to the editor's environment, and `stdin` is written to the process
---whole, which otherwise gets no input at all.
---@field run fun(argv: string[], opts: { cwd?: string, env?: table<string, string>, stdin?: string }, on_exit: fun(result: jin.RunResult))
---Process events until `cond` holds or `timeout` ms pass; false on timeout.
---@field wait fun(timeout: integer, cond: fun(): boolean): boolean
---Show `text`, which may span lines, and record it in the message history.
---@field echo fun(text: string, hl?: string)
---@field cwd fun(): string
---Absolute path of the current buffer, or "" when it has no name.
---@field bufname fun(): string
---`path` with symlinks resolved.
---@field realpath fun(path: string): string
---@field is_dir fun(path: string): boolean
---Fire the User autocmd `event` if any is defined.
---@field doautocmd fun(event: string)
---A monotonic clock in milliseconds, for measuring how much time passed.
---@field now fun(): number
---@field defer fun(ms: integer, fn: fun()): any
---@field cancel fun(timer: any)
---Open the buffer `name` with `opener` (`edit` by default) and modifiers
---such as `botright`, and return its number.
---@field open fun(name: string, opts: { opener?: string, mods?: string }): integer
---Replace the lines of `bufnr`, highlight `highlights` with the `groups` it
---defines, and make the buffer a read-only scratch buffer of `filetype`.
---Windows showing the buffer keep their view.
---@field render fun(bufnr: integer, content: jin.Content)
---The loaded buffers and their names.
---@field buffers fun(): { bufnr: integer, name: string }[]
---The name of `bufnr` while it is loaded, nil otherwise.
---@field buffer_name fun(bufnr: integer): string?
---Map <Plug>(jin-action-{name}) on `bufnr` for each name, in normal and
---visual mode, calling back into vim-jin with the lines acted on. With
---`defaults`, also map each of its keys to <Plug>(jin-action-{action}) in
---normal mode or in the mode a key names (third item, such as "x"), unless
---g:jin_{view}_disable_default_mappings is set or the buffer already maps
---the key itself. Map <Plug>(jin-{motion}) as well, in normal, visual and
---operator-pending mode, for each motion `defaults.motions` names (second
---item, such as "next-block"), calling back into vim-jin with the count
---typed, and map its keys to it as those of the actions are.
---@field define_actions fun(bufnr: integer, names: string[], defaults?: { view: string, keys: { [1]: string, [2]: string, [3]?: string }[], motions?: { [1]: string, [2]: string, [3]: string }[] })
---The mappings local to the current buffer.
---@field keymaps fun(): { lhs: string, rhs: string, mode: string }[]
---Ask for a line of text, completed as `completion` says unless it is ""; nil
---when nothing was entered.
---@field input fun(prompt: string, completion: string): string?
---Ask a yes-or-no question, no being the answer when none is given.
---@field confirm fun(prompt: string): boolean
---Put `text` in the register the user asked for (v:register).
---@field yank fun(text: string)
---Change the current directory with `scope`: "cd", "lcd" or "tcd".
---@field cd fun(scope: "cd"|"lcd"|"tcd", path: string)
---Whether the user splits windows for diffs vertically.
---@field vertical fun(): boolean
---Move the cursor of the window showing `bufnr` to line `lnum`.
---@field cursor fun(bufnr: integer, lnum: integer)
---Move the cursor of the current window, when it shows `bufnr`, to line
---`lnum` as a motion would, leaving where it was in the jumplist.
---@field jump fun(bufnr: integer, lnum: integer)
---The lines of `bufnr`.
---@field lines fun(bufnr: integer): string[]
---Mark `bufnr` as written, as a :w that succeeded does.
---@field mark_saved fun(bufnr: integer)
---Stop showing `bufnr` and wipe it out: a window showing it shows the buffer
---named `previous` instead, read again as :edit reads it, when given;
---otherwise each window showing it closes, and the tab page it was the last
---window of.
---@field leave fun(bufnr: integer, previous?: string)
---The line of the cursor in the window showing `bufnr`, nil when none does.
---@field line fun(bufnr: integer): integer?
---Highlight lines `first`..`last` of `bufnr` whole, as JinCursorEntry, in
---place of those highlighted before; with no lines, highlight none.
---@field highlight_lines fun(bufnr: integer, first?: integer, last?: integer)
---Highlight `lnums` of `bufnr` whole, as JinSelected, over JinCursorEntry and
---JinCursorChange where they fall on the same line, in place of those
---highlighted before. With `column`, put a column before every line, as
---virtual text ahead of any other: `column.text` and a space, as
---JinSelectedSign, on `column.lnums`, and as many blank cells on the others.
---@field highlight_selected fun(bufnr: integer, lnums: integer[], column?: { lnums: integer[], text: string })
---Highlight `lnums` of `bufnr` whole, as JinCursorChange, in place of
---those highlighted before.
---@field highlight_change fun(bufnr: integer, lnums: integer[])
---The value of g:jin_{name} as a string, nil when it is unset.
---@field setting fun(name: string): string?
---The value of g:jin_{name} when it is a dictionary, nil otherwise.
---@field setting_dict fun(name: string): table<string, any>?
---Turn a list handed over by the editor into a Lua table.
---@field list fun(value: any): any[]
---Turn a Lua table into a list to hand back to the editor.
---@field to_list fun(items: any[]): any

---@class jin.Content
---@field lines string[]
---@field highlights { line: integer, col: integer, end_col: integer, group: string }[] 1-based byte columns, end_col exclusive
---@field groups table<string, jin.AnsiStyle> the highlight groups to define
---@field filetype? string
---@field detect? string a path to take the filetype from, when `filetype` is nil
---@field title? string a short name for the buffer, kept in b:jin_title
---@field editable? boolean make the buffer one to edit, which :w hands back through BufWriteCmd
---@field fresh? boolean the first content since the buffer was loaded, which its filetype has to be set up for anew
---@field folds? { [1]: integer, [2]: integer }[] line ranges to fold, left open
---@field annotations? { text: string, group?: string }[][] per line, text shown before it as virtual text, not part of the line, padded so that the lines after it start in one column

---@class jin.RunResult
---@field code integer
---@field stdout string
---@field stderr string

if vim.api then
  return require("jin.host.nvim")
end
return require("jin.host.vim")
